CREATE TABLE IF NOT EXISTS "Campaign" (
  "id" TEXT NOT NULL,
  "title" TEXT NOT NULL,
  "slug" TEXT NOT NULL UNIQUE,
  "subtitle" TEXT,
  "type" TEXT NOT NULL,
  "category" TEXT,
  "status" TEXT NOT NULL DEFAULT 'DRAFT',
  "fontStyle" TEXT DEFAULT 'Classic',
  "primaryColor" TEXT DEFAULT '#991B1B',
  "colorMode" TEXT DEFAULT 'Light',
  "backgroundStyle" TEXT DEFAULT 'Simple',
  "backgroundTheme" TEXT,
  "organization" TEXT,
  "location" TEXT,
  "startDate" TIMESTAMP(3),
  "endDate" TIMESTAMP(3),
  "salesOpenDate" TIMESTAMP(3),
  "salesCloseDate" TIMESTAMP(3),
  "recurrence" TEXT DEFAULT 'once',
  "description" TEXT,
  "bannerUrl" TEXT,
  "bannerPublicId" TEXT,
  "bannerType" TEXT DEFAULT 'image',
  "logoUrl" TEXT,
  "logoPublicId" TEXT,
  "goalAmount" DOUBLE PRECISION,
  "raisedAmount" DOUBLE PRECISION DEFAULT 0,
  "donationConfig" JSONB,
  "seoData" JSONB,
  "publishedAt" TIMESTAMP(3),
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "Campaign_pkey" PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "CampaignMedia" (
  "id" TEXT NOT NULL,
  "campaignId" TEXT NOT NULL,
  "type" TEXT NOT NULL,
  "url" TEXT NOT NULL,
  "publicId" TEXT NOT NULL,
  "altText" TEXT,
  "category" TEXT,
  "sizeBytes" INTEGER,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "CampaignMedia_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "CampaignMedia_campaignId_fkey" FOREIGN KEY ("campaignId") REFERENCES "Campaign"("id") ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS "CampaignDonation" (
  "id" TEXT NOT NULL,
  "campaignId" TEXT NOT NULL,
  "donorFirstName" TEXT,
  "donorLastName" TEXT,
  "donorEmail" TEXT,
  "donorPhone" TEXT,
  "amount" DOUBLE PRECISION NOT NULL,
  "currency" TEXT NOT NULL DEFAULT 'usd',
  "recurring" BOOLEAN NOT NULL DEFAULT false,
  "recurringInterval" TEXT,
  "stripeSessionId" TEXT,
  "stripePaymentId" TEXT,
  "status" TEXT NOT NULL DEFAULT 'pending',
  "metadata" JSONB,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "CampaignDonation_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "CampaignDonation_campaignId_fkey" FOREIGN KEY ("campaignId") REFERENCES "Campaign"("id") ON DELETE CASCADE ON UPDATE CASCADE
);